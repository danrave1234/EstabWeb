function topLevelFromFieldPath(path: string): string {
  return path.split(".")[0].replace(/\[\]/g, "").trim()
}

export function getAllowedTopLevelFields(sectionKey: string): Set<string> | null {
  const fields = sectionKey === "hero" ? HERO_FIELD_SUPERSET : SECTION_FIELD_SCHEMA[sectionKey]
  if (!fields) return null
  return new Set(fields.map(topLevelFromFieldPath).filter(Boolean))
}

